"""Adapt a Kona palette to Paseo's shared surface/color roles."""

import argparse
import json
from pathlib import Path
import re


def color(tokens, name):
    value = tokens[name]
    if not isinstance(value, str) or not re.fullmatch(r'#[0-9a-fA-F]{6}', value):
        raise ValueError(f'Invalid Kona color for {name}: expected an opaque hex color')
    return value


def mix(first, second, amount):
    channels = []
    for offset in (1, 3, 5):
        a = int(first[offset:offset + 2], 16)
        b = int(second[offset:offset + 2], 16)
        channels.append(f'{round(a * (1 - amount) + b * amount):02X}')
    return '#' + ''.join(channels)


def render(tokens):
    # Paseo shares border with message fills, and ring with extra-muted text.
    # Kona's desktop outline/focus tokens need softer values in those roles.
    colors = {
        'background': mix(color(tokens, 'bg.0'), color(tokens, 'bg.1'), 0.55),
        'foreground': mix(color(tokens, 'bg.0'), color(tokens, 'text.primary'), 0.94),
        'raised': mix(color(tokens, 'bg.1'), color(tokens, 'bg.2'), 0.30),
        'control': color(tokens, 'bg.2'),
        'border': mix(color(tokens, 'bg.2'), color(tokens, 'accent.border'), 0.20),
        'accent': color(tokens, 'accent.primary'),
        'mutedForeground': mix(color(tokens, 'text.disabled'), color(tokens, 'text.secondary'), 0.25),
        'ring': mix(color(tokens, 'bg.2'), color(tokens, 'text.disabled'), 0.80),
    }
    properties = '\n'.join(f'      {name}: {json.dumps(value)},' for name, value in colors.items())
    return '''// Generated by tools/sync-theme.py; edit the source palette instead.
import type { PluginClientContext } from "@getpaseo/plugin/client";

export default function contribute(client: PluginClientContext) {
  client.addTheme({
    id: "kona-dark",
    name: "Kona",
    appearance: "dark",
    colors: {
''' + properties + '''
    },
  });
  return () => {};
}
'''


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=root / 'palette.json')
    parser.add_argument('--check', action='store_true', help='Check the generated file without writing')
    args = parser.parse_args()
    try:
        output = render(json.loads(args.source.read_text()))
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.error(str(error))
    destination = root / 'index.client.ts'
    if args.check:
        if destination.read_text() != output:
            parser.error('index.client.ts differs from the selected palette; regenerate it')
        print('Theme matches the source palette')
    else:
        destination.write_text(output)
        print(f'Updated {destination} from {args.source}')


if __name__ == '__main__':
    main()
